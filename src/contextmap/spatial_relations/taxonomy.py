"""Every predicate's semantics, keyed by predicate."""


def predicate_spec(predicate: RelationPredicate) -> PredicateSpec:
    """Look up the semantics of a predicate.

    Args:
        predicate: A canonical predicate.

    Returns:
        Its direction, symmetry, inverse, frame requirement and meaning.
    """
    return PREDICATE_SPECS[predicate]
